import * as THREE from "three";
import { buildArmillary, buildMonoliths, buildPillars, buildTerrain } from "../src/intro/world";
import { CameraRig } from "../src/intro/camera";
import { CORE_Y } from "../src/intro/config";
import { polishedFrag, polishedVert } from "../src/intro/shaders";
const U: any = { uTime:{value:0}, uCore:{value:new THREE.Vector4(0,CORE_Y,0,1)}, uCorePos:{value:new THREE.Vector3()}, uMono:{value:Array.from({length:10},()=>new THREE.Vector4())}, uExposure:{value:1}, uFogColor:{value:new THREE.Color()}, uFogDensity:{value:0.006}, uCharge:{value:0}, uWaveC:{value:new THREE.Vector2()}, uWaveR:{value:0}, uWaveW:{value:40}, uShockR:{value:0}, uShockW:{value:1}, uShockAmp:{value:0}, uResY:{value:1080}, uBT:{value:-1} };
const root = new THREE.Group();
root.add(buildTerrain(U));
root.add(buildPillars(U));
const monos = buildMonoliths(U, 4);
monos.forEach((m) => root.add(m.group));
const mat = new THREE.ShaderMaterial({ vertexShader: polishedVert, fragmentShader: polishedFrag, uniforms: { ...U, uForm:{value:1}, uSweep:{value:0}, uGlow:{value:1}, uSpan:{value:2} } });
root.add(buildArmillary(mat).group);
const rig = new CameraRig(monos.map((m)=>({x:m.base.x,z:m.base.z,r:6})));
const pose = rig.sample(14);
console.log("cam", pose.pos.toArray().map(n=>n.toFixed(2)), "target", pose.target.toArray().map(n=>n.toFixed(2)));
console.log("mono bases:", monos.map((m,i)=>`#${i} (${m.base.x.toFixed(1)},${m.base.z.toFixed(1)}) d=${Math.hypot(m.base.x-pose.pos.x, m.base.z-pose.pos.z).toFixed(1)}`).join("  "));
const cam = new THREE.PerspectiveCamera(pose.fov, 16/9, 0.1, 2000);
cam.position.copy(pose.pos); cam.lookAt(pose.target); cam.updateMatrixWorld(true); cam.updateProjectionMatrix();
const dir = new THREE.Vector3(); cam.getWorldDirection(dir);
console.log("view dir", dir.toArray().map(n=>n.toFixed(2)));
root.updateMatrixWorld(true);
const rows: [string, number, number][] = [];
root.traverse((o) => {
  const m = o as THREE.Mesh;
  if (!m.isMesh || !m.visible) return;
  const g = m.geometry as THREE.BufferGeometry;
  if (!g.boundingSphere) g.computeBoundingSphere();
  const c = g.boundingSphere!.center.clone().applyMatrix4(m.matrixWorld);
  const d = c.distanceTo(cam.position);
  const ahead = c.clone().sub(cam.position).normalize().dot(dir);
  rows.push([`${m.parent?.name || m.name || m.type}/${g.type}`, d, ahead]);
});
rows.sort((a,b)=>a[1]-b[1]);
console.log(rows.slice(0,10).map(([n,d,a])=>`${n} d=${d.toFixed(1)} dot=${a.toFixed(2)}`).join("\n"));
